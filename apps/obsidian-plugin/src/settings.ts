/**
 * Obsidian Duet Agent - Plugin Settings Tab
 */

import { App, PluginSettingTab, Setting, Notice } from 'obsidian';
import type ObsidianDuetPlugin from '../main.js';
import { SpecialistRole } from '../../../packages/contracts/src/types.js';

export class DuetSettingTab extends PluginSettingTab {
  plugin: ObsidianDuetPlugin;

  constructor(app: App, plugin: ObsidianDuetPlugin) {
    super(app, plugin);
    this.plugin = plugin;
  }

  display(): void {
    const { containerEl } = this;
    containerEl.empty();

    containerEl.createEl('h2', { text: 'Obsidian Duet Agent — Settings' });

    // --- Windows Companion Connection ---
    containerEl.createEl('h3', { text: 'Windows Background Companion' });

    new Setting(containerEl)
      .setName('Companion Service URL')
      .setDesc('Loopback endpoint where the Windows companion is running.')
      .addText((text) =>
        text
          .setPlaceholder('http://127.0.0.1:3842')
          .setValue(this.plugin.settings.companionUrl)
          .onChange(async (val) => {
            this.plugin.settings.companionUrl = val.trim();
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Pairing Secret Token')
      .setDesc('Authentication bearer token generated by the companion during pairing.')
      .addText((text) =>
        text
          .setPlaceholder('Paste companion token…')
          .setValue(this.plugin.settings.companionToken)
          .onChange(async (val) => {
            this.plugin.settings.companionToken = val.trim();
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Test Connection')
      .setDesc('Probe companion health, version, and active provider backends.')
      .addButton((btn) =>
        btn.setButtonText('Test Connection').onClick(async () => {
          btn.setDisabled(true);
          btn.setButtonText('Testing…');
          try {
            const res = await fetch(`${this.plugin.settings.companionUrl.replace(/\/+$/, '')}/api/health`, {
              headers: this.plugin.settings.companionToken
                ? { Authorization: `Bearer ${this.plugin.settings.companionToken}` }
                : {},
            });
            if (res.ok) {
              const data = await res.json();
              new Notice(`Companion Connected! Version: ${data.version}, Providers: ${data.availableProviders.join(', ')}`);
            } else {
              new Notice(`Companion returned HTTP ${res.status}: ${res.statusText}`);
            }
          } catch (err) {
            new Notice(`Cannot reach companion at ${this.plugin.settings.companionUrl}. Ensure companion service is running.`);
          } finally {
            btn.setDisabled(false);
            btn.setButtonText('Test Connection');
          }
        })
      );

    // --- Provider & Model Defaults ---
    containerEl.createEl('h3', { text: 'Inference Provider & Model' });

    new Setting(containerEl)
      .setName('Default Provider')
      .setDesc('Select the primary inference engine.')
      .addDropdown((dd) =>
        dd
          .addOption('ollama', 'Ollama (Local API)')
          .addOption('local-gguf', 'Local GGUF (node-llama-cpp)')
          .addOption('anthropic', 'Anthropic Claude')
          .addOption('openai', 'OpenAI')
          .addOption('compatible', 'Custom Compatible Endpoint')
          .setValue(this.plugin.settings.defaultProviderId)
          .onChange(async (val) => {
            this.plugin.settings.defaultProviderId = val;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Default Model ID')
      .setDesc('Model identifier sent in API requests (e.g. llama3.2, claude-3-5-sonnet-20241022, gpt-4o).')
      .addText((text) =>
        text
          .setValue(this.plugin.settings.defaultModelId)
          .onChange(async (val) => {
            this.plugin.settings.defaultModelId = val.trim();
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Default Specialist Role')
      .setDesc('Agent profile assigned when opening a new chat.')
      .addDropdown((dd) =>
        dd
          .addOption('coordinator', 'Coordinator')
          .addOption('researcher', 'Researcher')
          .addOption('coder', 'Coder')
          .addOption('reviewer', 'Reviewer')
          .addOption('vault-assistant', 'Vault Assistant')
          .setValue(this.plugin.settings.activeSpecialistRole)
          .onChange(async (val) => {
            this.plugin.settings.activeSpecialistRole = val as SpecialistRole;
            await this.plugin.saveSettings();
          })
      );

    // --- Permissions & Approval Controls ---
    containerEl.createEl('h3', { text: 'Security & Permission Policies' });

    new Setting(containerEl)
      .setName('Require Approval for Vault Edits')
      .setDesc('Always show diff review modal before modifying any existing note in your vault.')
      .addToggle((toggle) =>
        toggle
          .setValue(this.plugin.settings.requireApprovalForVaultEdits)
          .onChange(async (val) => {
            this.plugin.settings.requireApprovalForVaultEdits = val;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Require Approval for External Project Writes')
      .setDesc('Require approval before editing files in registered external project folders.')
      .addToggle((toggle) =>
        toggle
          .setValue(this.plugin.settings.requireApprovalForExternalWrites)
          .onChange(async (val) => {
            this.plugin.settings.requireApprovalForExternalWrites = val;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Require Approval for Terminal Commands')
      .setDesc('Require explicit confirmation before running commands via the Windows companion.')
      .addToggle((toggle) =>
        toggle
          .setValue(this.plugin.settings.requireApprovalForTerminal)
          .onChange(async (val) => {
            this.plugin.settings.requireApprovalForTerminal = val;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Require Approval for Browser Actions')
      .setDesc('Prompt before executing form fills or download actions in Playwright.')
      .addToggle((toggle) =>
        toggle
          .setValue(this.plugin.settings.requireApprovalForBrowserActions)
          .onChange(async (val) => {
            this.plugin.settings.requireApprovalForBrowserActions = val;
            await this.plugin.saveSettings();
          })
      );

    new Setting(containerEl)
      .setName('Vault Conversations Folder')
      .setDesc('Folder where chats are archived as Markdown notes.')
      .addText((text) =>
        text
          .setPlaceholder('Duet Chats')
          .setValue(this.plugin.settings.conversationsFolder)
          .onChange(async (val) => {
            this.plugin.settings.conversationsFolder = val.trim() || 'Duet Chats';
            await this.plugin.saveSettings();
          })
      );
  }
}
