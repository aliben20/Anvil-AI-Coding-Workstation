import esbuild from 'esbuild';
import process from 'process';
import fs from 'fs';
import path from 'path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Duet Agent Plugin
*/
`;

const isProd = process.argv[2] === 'production';
const outdir = path.resolve('apps/obsidian-plugin/dist');
const vaultPluginDir = path.resolve('dev-vault/.obsidian/plugins/obsidian-duet-agent');

fs.mkdirSync(outdir, { recursive: true });
fs.mkdirSync(vaultPluginDir, { recursive: true });

async function copyAssets() {
  const assets = ['manifest.json', 'styles.css'];
  for (const asset of assets) {
    const src = path.resolve('apps/obsidian-plugin', asset);
    if (fs.existsSync(src)) {
      fs.copyFileSync(src, path.join(outdir, asset));
      fs.copyFileSync(src, path.join(vaultPluginDir, asset));
    }
  }
}

async function build() {
  const context = await esbuild.context({
    banner: {
      js: banner,
    },
    entryPoints: ['apps/obsidian-plugin/main.ts'],
    bundle: true,
    external: [
      'obsidian',
      'electron',
      '@codemirror/autocomplete',
      '@codemirror/collab',
      '@codemirror/commands',
      '@codemirror/language',
      '@codemirror/lint',
      '@codemirror/search',
      '@codemirror/state',
      '@codemirror/view',
      '@lezer/common',
      '@lezer/highlight',
      '@lezer/lr',
    ],
    format: 'cjs',
    target: 'es2022',
    logLevel: 'info',
    sourcemap: isProd ? false : 'inline',
    treeShaking: true,
    outfile: path.join(outdir, 'main.js'),
  });

  if (isProd) {
    await context.rebuild();
    await copyAssets();
    // Also copy built main.js to dev-vault
    fs.copyFileSync(path.join(outdir, 'main.js'), path.join(vaultPluginDir, 'main.js'));
    console.log('Build complete. Bundled plugin into dist/ and dev-vault/.obsidian/plugins/obsidian-duet-agent/');
    process.exit(0);
  } else {
    await context.rebuild();
    await copyAssets();
    fs.copyFileSync(path.join(outdir, 'main.js'), path.join(vaultPluginDir, 'main.js'));
    console.log('Build complete. Watching for changes...');
    await context.watch();
  }
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
